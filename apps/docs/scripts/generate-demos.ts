// Writes components/demos/index.ts: every file under components/demos/<component>/
// becomes a demo named "<component>/<file>", usable as <Demo name="…" /> in a page.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "../components/demos");

const names = readdirSync(dir)
  .filter((entry) => statSync(join(dir, entry)).isDirectory())
  .sort()
  .flatMap((component) =>
    readdirSync(join(dir, component))
      .filter((file) => file.endsWith(".tsx"))
      .sort()
      .map((file) => `${component}/${file.slice(0, -4)}`),
  );

const identifier = (name: string) =>
  name
    .split(/[/-]/)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");

writeFileSync(
  join(dir, "index.ts"),
  `// Generated by scripts/generate-demos.ts: do not edit.
import type { ComponentType } from "react";
${names.map((name) => `import ${identifier(name)} from "./${name}";`).join("\n")}

/** Every live demo, by path under components/demos (the source shown is read from that file). */
export const demos: Record<string, ComponentType> = {
${names.map((name) => `  "${name}": ${identifier(name)},`).join("\n")}
};
`,
);
console.log(`${names.length} demos`);
