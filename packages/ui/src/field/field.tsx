import { cn } from "@irisui/utils";
import * as LabelPrimitive from "@radix-ui/react-label";
import {
  createContext,
  forwardRef,
  useContext,
  useEffect,
  useId,
  useLayoutEffect,
  useMemo,
  useState,
  type ComponentPropsWithoutRef,
  type HTMLAttributes,
} from "react";

const useIsomorphicLayoutEffect = typeof window === "undefined" ? useEffect : useLayoutEffect;

interface FieldContextValue {
  controlId: string;
  labelId: string;
  descriptionId: string;
  errorId: string;
  hasDescription: boolean;
  hasError: boolean;
  invalid: boolean;
  disabled: boolean;
  required: boolean;
  setHasDescription: (value: boolean) => void;
  setHasError: (value: boolean) => void;
}

const FieldContext = createContext<FieldContextValue | null>(null);

export interface FieldProps extends HTMLAttributes<HTMLDivElement> {
  /** Marks the control invalid. Defaults to true when a `FieldError` is rendered. */
  invalid?: boolean;
  disabled?: boolean;
  required?: boolean;
  /** Id given to the control. Generated by default. */
  id?: string;
}

/**
 * Groups a label, a control, a description and an error message, and links
 * them: `htmlFor`, `aria-describedby`, `aria-invalid`, `required`, `disabled`.
 */
export const Field = forwardRef<HTMLDivElement, FieldProps>(function Field(
  { invalid, disabled = false, required = false, id, className, ...props },
  ref,
) {
  const generated = useId();
  const controlId = id ?? `${generated}-control`;
  const [hasDescription, setHasDescription] = useState(false);
  const [hasError, setHasError] = useState(false);
  const value = useMemo<FieldContextValue>(
    () => ({
      controlId,
      labelId: `${generated}-label`,
      descriptionId: `${generated}-description`,
      errorId: `${generated}-error`,
      hasDescription,
      hasError,
      invalid: invalid ?? hasError,
      disabled,
      required,
      setHasDescription,
      setHasError,
    }),
    [controlId, generated, hasDescription, hasError, invalid, disabled, required],
  );
  return (
    <FieldContext.Provider value={value}>
      <div
        ref={ref}
        data-invalid={value.invalid ? "" : undefined}
        data-disabled={disabled ? "" : undefined}
        className={cn("flex flex-col gap-2", className)}
        {...props}
      />
    </FieldContext.Provider>
  );
});

export type FieldLabelProps = ComponentPropsWithoutRef<typeof LabelPrimitive.Root>;

export const FieldLabel = forwardRef<HTMLLabelElement, FieldLabelProps>(function FieldLabel(
  { className, htmlFor, id, ...props },
  ref,
) {
  const field = useContext(FieldContext);
  return (
    <LabelPrimitive.Root
      ref={ref}
      id={id ?? field?.labelId}
      htmlFor={htmlFor ?? field?.controlId}
      className={cn("text-md font-medium text-text", className)}
      {...props}
    />
  );
});

export const FieldDescription = forwardRef<
  HTMLParagraphElement,
  HTMLAttributes<HTMLParagraphElement>
>(function FieldDescription({ className, id, ...props }, ref) {
  const field = useContext(FieldContext);
  const setHasDescription = field?.setHasDescription;
  useIsomorphicLayoutEffect(() => {
    setHasDescription?.(true);
    return () => setHasDescription?.(false);
  }, [setHasDescription]);
  return (
    <p
      ref={ref}
      id={id ?? field?.descriptionId}
      className={cn("m-0 text-sm text-text-muted", className)}
      {...props}
    />
  );
});

/** Error message. Rendering it marks the field invalid, unless `Field` sets `invalid`. */
export const FieldError = forwardRef<HTMLParagraphElement, HTMLAttributes<HTMLParagraphElement>>(
  function FieldError({ className, id, children, ...props }, ref) {
    const field = useContext(FieldContext);
    const setHasError = field?.setHasError;
    const hasContent = children !== undefined && children !== null && children !== false;
    useIsomorphicLayoutEffect(() => {
      if (!hasContent) return;
      setHasError?.(true);
      return () => setHasError?.(false);
    }, [setHasError, hasContent]);
    if (!hasContent) return null;
    return (
      <p
        ref={ref}
        id={id ?? field?.errorId}
        className={cn("m-0 text-sm font-bold text-danger-text", className)}
        {...props}
      >
        {children}
      </p>
    );
  },
);

export interface FieldControlProps {
  id?: string | undefined;
  "aria-describedby"?: string | undefined;
  "aria-invalid"?: boolean | "true" | "false" | "grammar" | "spelling" | undefined;
  required?: boolean | undefined;
  disabled?: boolean | undefined;
}

export interface FieldControl<P> {
  /** The control's props, completed by its `Field`. */
  control: P;
  invalid: boolean;
  /** Id of the `FieldLabel`, for controls a `<label for>` cannot name (radio groups). */
  labelId: string | undefined;
}

/**
 * Props a control takes from its `Field`. Its own props win; `aria-describedby`
 * is merged. Outside a `Field`, the props are returned unchanged.
 */
export function useFieldControl<P extends FieldControlProps>(props: P): FieldControl<P> {
  const field = useContext(FieldContext);
  const ownInvalid = props["aria-invalid"] === true || props["aria-invalid"] === "true";
  if (!field) return { control: props, invalid: ownInvalid, labelId: undefined };
  const describedBy =
    [
      props["aria-describedby"],
      field.hasDescription ? field.descriptionId : undefined,
      field.hasError ? field.errorId : undefined,
    ]
      .filter(Boolean)
      .join(" ") || undefined;
  const invalid = ownInvalid || field.invalid;
  return {
    control: {
      ...props,
      id: props.id ?? field.controlId,
      "aria-describedby": describedBy,
      "aria-invalid": invalid || undefined,
      required: props.required ?? (field.required || undefined),
      disabled: props.disabled ?? (field.disabled || undefined),
    },
    invalid,
    labelId: field.labelId,
  };
}
